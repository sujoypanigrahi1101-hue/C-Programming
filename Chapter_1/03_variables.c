#include<stdio.h>
int main()
{
    int a = 1;
    printf("The value of a is: %d\n", a);

    float b = 2.5;
    printf("The value of b is: %f\n", b);

    char c = 'C';
    printf("The value of c is: %c\n", c);

    double d = 3.14159;
    printf("The value of d is: %f\n", d);

    long e = 1000000;
    printf("The value of e is: %ld\n", e);

    long long f = 10000000000;
    printf("The value of f is: %lld\n", f);

    unsigned int g = 10;
    printf("The value of g is: %u\n", g);

    char h[14] = "Hello, World!";
    printf("The value of h is: %s\n", h);

    return 0;


}